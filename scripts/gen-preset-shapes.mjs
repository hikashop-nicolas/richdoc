// Turn ECMA-376's presetShapeDefinitions.xml into src/adapters/docx/preset-shapes.ts: each preset's
// adjust defaults, guides and paths in a compact table for drawingml-geom.ts.
// Usage: node scripts/gen-preset-shapes.mjs path/to/presetShapeDefinitions.xml
// The XML ships with ECMA-376 Part 1 (also in Apache POI, poi/src/main/resources/org/apache/poi/sl/draw/geom/).
import { readFileSync, writeFileSync } from "node:fs";

const xml = readFileSync(process.argv[2], "utf8");
const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w:]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

// A small tree from the tags: the file is plain, regular XML.
const root = { tag: "#root", a: {}, kids: [] };
const stack = [root];
for (const m of xml.matchAll(/<(\/?)([A-Za-z][\w:]*)([^>]*?)(\/?)>/g)) {
  const [, close, tag, rest, self] = m;
  if (close) { stack.pop(); continue; }
  const el = { tag, a: attrs(rest), kids: [] };
  stack.at(-1).kids.push(el);
  if (!self) stack.push(el);
}
const kid = (el, tag) => el.kids.find((k) => k.tag === tag);
const gds = (el) => (el ? el.kids.filter((k) => k.tag === "gd").map((g) => [g.a.name, g.a.fmla]) : []);

const out = {};
const shapes = root.kids[0].kids;
for (const shape of shapes) {
  const paths = [];
  for (const p of kid(shape, "pathLst")?.kids ?? []) {
    const cmds = [];
    for (const c of p.kids) {
      const pts = c.kids.filter((k) => k.tag === "pt").flatMap((pt) => [pt.a.x, pt.a.y]);
      if (c.tag === "moveTo") cmds.push("M", ...pts);
      else if (c.tag === "lnTo") cmds.push("L", ...pts);
      else if (c.tag === "cubicBezTo") cmds.push("C", ...pts);
      else if (c.tag === "quadBezTo") cmds.push("Q", ...pts);
      else if (c.tag === "arcTo") cmds.push("A", c.a.wR, c.a.hR, c.a.stAng, c.a.swAng);
      else if (c.tag === "close") cmds.push("Z");
    }
    paths.push([Number(p.a.w ?? 0), Number(p.a.h ?? 0), p.a.fill ?? "norm", p.a.stroke === "false" ? 0 : 1, cmds.join(" ")]);
  }
  out[shape.tag] = [gds(kid(shape, "avLst")), gds(kid(shape, "gdLst")), paths];
}

const body = JSON.stringify(out);
writeFileSync(
  new URL("../src/adapters/docx/preset-shapes.ts", import.meta.url),
  `// Generated by scripts/gen-preset-shapes.mjs from ECMA-376 Part 1's presetShapeDefinitions.xml
// (Ecma International). Do not edit by hand.
// Per preset: [adjust defaults, guides, paths]; a guide is [name, formula]; a path is
// [w, h, fill, stroke, commands] (w and h 0 when the path uses the shape's own size).

export type PresetPath = [number, number, string, number, string];
export type Preset = [[string, string][], [string, string][], PresetPath[]];

export const PRESETS: Record<string, Preset> = JSON.parse(${JSON.stringify(body)});
`,
);
console.log(Object.keys(out).length, "presets,", body.length, "bytes");
